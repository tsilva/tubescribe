"""Build an earlier-version archive from a frozen historical schema and sample records."""

import re
import sqlite3
from contextlib import closing
from pathlib import Path

SQL = (Path(__file__).parent / "fixtures" / "archive-v4.sql").read_text()


def write_v4(source, destination):
    with closing(sqlite3.connect(destination)) as db, db:
        db.executescript(SQL)
        for (table,) in db.execute("SELECT name FROM sqlite_master WHERE type='table'").fetchall():
            if table == "schema_migrations":
                continue
            names = [row[1] for row in db.execute(f"PRAGMA table_info({table})")]
            for row in source.execute(f"SELECT {','.join(names)} FROM {table}"):
                db.execute(
                    f"INSERT INTO {table} VALUES({','.join('?' for _ in names)})", tuple(row)
                )


def load_postgres_v4(db, source):
    # PostgreSQL first shipped with schema 5. Exercise its supported migration path
    # using the equivalent schema-4 archive layout, with the historical column set.
    order = (
        "channels",
        "videos",
        "profiles",
        "jobs",
        "discovery",
        "transcripts",
        "diarization_profiles",
        "diarizations",
        "postprocessings",
        "artifacts",
        "claims",
        "submissions",
        "submission_results",
        "agent_runs",
        "attempts",
        "runtime_events",
        "schema_migrations",
    )
    with closing(sqlite3.connect(source)) as old, db:
        for table in order:
            definition = old.execute(
                "SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (table,)
            ).fetchone()[0]
            definition = re.sub(r"\bREAL\b", "DOUBLE PRECISION", definition)
            if table in {"jobs", "runtime_events"}:
                definition = definition.replace(
                    "id INTEGER PRIMARY KEY",
                    "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                )
            db.execute(definition)
            names = [row[1] for row in old.execute(f"PRAGMA table_info({table})")]
            for row in old.execute(f"SELECT {','.join(names)} FROM {table}"):
                db.execute(
                    f"INSERT INTO {table} VALUES({','.join('?' for _ in names)})", tuple(row)
                )
        db.execute(
            old.execute(
                "SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL"
            ).fetchone()[0]
        )
        for table in ("jobs", "runtime_events"):
            db.execute(
                f"SELECT setval(pg_get_serial_sequence('{table}','id'),COALESCE(MAX(id),1),COUNT(*)>0) FROM {table}"
            )
